"""Post-training int8 quantization + export for the SystemC accelerator.
Integer-only inference: int8 weights/activations, int32 accumulators,
requantize with  out = clamp((acc*M + 2^(S-1)) >> S, 0, 127)   (ReLU folded into clamp).
Writes ../systemc/data/{weights.bin,test_images.bin,test_labels.bin,golden_logits.bin} and ../systemc/src/model_params.h
"""
import os, numpy as np
from numpy.lib.stride_tricks import sliding_window_view as swv
import train_mnist as T

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "systemc")
os.makedirs(os.path.join(OUT, "data"), exist_ok=True)
os.makedirs(os.path.join(OUT, "src"), exist_ok=True)
S = 24
NTEST = 200

fm = np.load(os.path.join(HERE, "model_float.npz"))
for k in fm.files:
    T.P[k] = fm[k]

Xtr = T.load_images("train-images-idx3-ubyte.gz")
Xte = T.load_images("t10k-images-idx3-ubyte.gz")
yte = T.load_labels("t10k-labels-idx1-ubyte.gz")

# ---------- float accuracy + calibration ----------
xf = Xte.astype(np.float32)[:, None] / 255
pf = np.concatenate([T.forward(xf[i:i + 500]).argmax(1) for i in range(0, 10000, 500)])
print(f"float accuracy : {np.mean(pf == yte) * 100:.2f}%")

cal = Xtr[:2000].astype(np.float32)[:, None] / 255
z1, _ = T.conv_fwd(cal, T.P["w1"], T.P["b1"]); a1 = np.maximum(z1, 0)
p1 = T.pool_fwd(a1)
z2, _ = T.conv_fwd(p1, T.P["w2"], T.P["b2"]); a2 = np.maximum(z2, 0)
p2 = T.pool_fwd(a2)
a3 = np.maximum(p2.reshape(2000, -1) @ T.P["w3"].T + T.P["b3"], 0)
s_act = [np.percentile(a, 99.9) / 127 for a in (a1, a2, a3)]
s_in = [1 / 127, s_act[0], s_act[1], s_act[2]]

# ---------- quantize ----------
Wq, Bq, Mq = [], [], []
for i, (w, b) in enumerate([("w1", "b1"), ("w2", "b2"), ("w3", "b3"), ("w4", "b4")]):
    W, B = T.P[w], T.P[b]
    sw = np.abs(W).max() / 127
    wq = np.clip(np.round(W / sw), -127, 127).astype(np.int8)
    bq = np.round(B / (s_in[i] * sw)).astype(np.int32)
    Wq.append(wq); Bq.append(bq)
    if i < 3:
        M = int(round(s_in[i] * sw / s_act[i] * (1 << S)))
        assert 0 < M < 2 ** 31
        Mq.append(M)
print("requant multipliers M1..M3:", Mq)


def requant(acc, M):
    return np.clip((acc.astype(np.int64) * M + (1 << (S - 1))) >> S, 0, 127)


def conv_int(x, W, b):
    N, C, H, Wd = x.shape
    F = W.shape[0]; Ho, Wo = H - 2, Wd - 2
    cols = swv(x.astype(np.float64), (3, 3), axis=(2, 3)).transpose(0, 2, 3, 1, 4, 5).reshape(N * Ho * Wo, C * 9)
    acc = np.rint(cols @ W.reshape(F, -1).astype(np.float64).T).astype(np.int64) + b
    return acc.reshape(N, Ho, Wo, F).transpose(0, 3, 1, 2)


def forward_int(xq):
    a = requant(conv_int(xq, Wq[0], Bq[0]), Mq[0]); a = T.pool_fwd(a)
    a = requant(conv_int(a, Wq[1], Bq[1]), Mq[1]); a = T.pool_fwd(a)
    f = a.reshape(len(a), -1).astype(np.float64)
    a = requant(np.rint(f @ Wq[2].astype(np.float64).T).astype(np.int64) + Bq[2], Mq[2])
    return np.rint(a.astype(np.float64) @ Wq[3].astype(np.float64).T).astype(np.int64) + Bq[3]


def in_quant(img):  # uint8 0..255 -> 0..127
    return np.rint(img.astype(np.float64) / 255 * 127).astype(np.int64)


xq = in_quant(Xte)[:, None]
logits = np.concatenate([forward_int(xq[i:i + 500]) for i in range(0, 10000, 500)])
pq = logits.argmax(1)
print(f"int8 accuracy  : {np.mean(pq == yte) * 100:.2f}%   (SystemC must match this bit-exactly)")

# ---------- export ----------
with open(os.path.join(OUT, "data", "weights.bin"), "wb") as f:
    for w in Wq: f.write(w.tobytes())
    for b in Bq: f.write(b.astype("<i4").tobytes())
Xte[:NTEST].tofile(os.path.join(OUT, "data", "test_images.bin"))
yte[:NTEST].tofile(os.path.join(OUT, "data", "test_labels.bin"))
logits[:NTEST].astype("<i4").tofile(os.path.join(OUT, "data", "golden_logits.bin"))
with open(os.path.join(OUT, "src", "model_params.h"), "w") as f:
    f.write("// auto-generated by quantize_export.py\n#pragma once\n#include <cstdint>\n")
    f.write(f"constexpr int REQ_SHIFT = {S};\n")
    for i, M in enumerate(Mq):
        f.write(f"constexpr int32_t REQ_M{i + 1} = {M};\n")
    f.write(f"constexpr int NUM_TEST = {NTEST};\n")
np.savez(os.path.join(HERE, "quant_summary.npz"), float_acc=np.mean(pf == yte), int_acc=np.mean(pq == yte))
print("exported OK")
